// Builds src/assets/emoji.ts from @lobehub/fluent-emoji-3d (MIT, WebP 256 px).
// If scripts/emoji-urls.json exists (asset store URLs from the artifact), those are used;
// otherwise images are inlined as data: URIs for local previews.
// Usage: node scripts/gen-emoji.mjs [--stage <dir>]   (--stage copies the files for upload)
import fs from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const src = path.join(root, "node_modules/@lobehub/fluent-emoji-3d/assets")

export const EMOJI = {
  sprout: "1f331", // 🌱
  droplet: "1f4a7", // 💧
  testTube: "1f9ea", // 🧪
  thermometer: "1f321-fe0f", // 🌡️
  chart: "1f4c8", // 📈
  bell: "1f514", // 🔔
  herb: "1f33f", // 🌿
  sun: "2600-fe0f", // ☀️
  pottedPlant: "1fab4", // 🪴
  book: "1f4d6", // 📖
  notebook: "1f4d3", // 📓
  toolbox: "1f9f0", // 🧰
  compass: "1f9ed", // 🧭
  gear: "2699-fe0f", // ⚙️
  camera: "1f4f7", // 📷
  scissors: "2702-fe0f", // ✂️
  scales: "2696-fe0f", // ⚖️
  wind: "1f32c-fe0f", // 🌬️
  jar: "1fad9", // 🫙
  bulb: "1f4a1", // 💡
  moon: "1f319", // 🌙
  warning: "26a0-fe0f", // ⚠️
}

const args = process.argv.slice(2)
const stage = args.includes("--stage") ? args[args.indexOf("--stage") + 1] : null
const urlsFile = path.join(root, "scripts/emoji-urls.json")
const inline = args.includes("--inline") // local previews: the asset store is not reachable outside claude.ai
const urls = !inline && fs.existsSync(urlsFile) ? JSON.parse(fs.readFileSync(urlsFile, "utf8")) : {}

if (stage) fs.mkdirSync(stage, { recursive: true })
const lines = []
for (const [name, code] of Object.entries(EMOJI)) {
  const file = path.join(src, `${code}.webp`)
  if (!fs.existsSync(file)) throw new Error(`missing ${file}`)
  if (stage) fs.copyFileSync(file, path.join(stage, `${name}.webp`))
  const value = urls[name] ?? `data:image/webp;base64,${fs.readFileSync(file).toString("base64")}`
  lines.push(`  ${name}: ${JSON.stringify(value)},`)
}

const out = `// Generated by scripts/gen-emoji.mjs — do not edit.
// Microsoft Fluent Emoji 3D via @lobehub/fluent-emoji-3d (MIT).
export const EMOJI = {
${lines.join("\n")}
} as const
export type EmojiName = keyof typeof EMOJI
`
fs.writeFileSync(path.join(root, "src/assets/emoji.ts"), out)
console.log(`emoji.ts: ${Object.keys(EMOJI).length} images, ${Object.keys(urls).length} from asset store`)
